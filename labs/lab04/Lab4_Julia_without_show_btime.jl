# #### 2.3.1. Диагонализация матриц
#
# Матрицы в задании симметричные. Для них используем `eigen(Symmetric(A))`. Если `V` — матрица собственных векторов, а `D` — диагональная матрица собственных значений, то выполняется `V' * A * V ≈ D` и `V * D * V' ≈ A`.

# %%
function show_diagonalization(A, label)
    A_float = Float64.(A)
    F = eigen(Symmetric(A_float))
    V = F.vectors
    D = Diagonal(F.values)

    println("\n", label)
    display(F.values)
    println("Диагональная матрица D:")
    display(Matrix(D))
    println("Матрица собственных векторов V:")
    display(V)
    println("Проверка V' * A * V ≈ D: ", isapprox(V' * A_float * V, Matrix(D)))
    println("Проверка V * D * V' ≈ A: ", isapprox(V * D * V', A_float))
end

show_diagonalization([1 -2; -2 1], "4.4.3.1(a)")
show_diagonalization([1 -2; -2 3], "4.4.3.1(b)")
show_diagonalization([1 -2 0; -2 1 2; 0 2 0], "4.4.3.1(c)")

