# ### 2.2. Системы линейных уравнений (4.4.2)

# Функция ниже сравнивает ранг матрицы коэффициентов и ранг расширенной матрицы. Так мы отличаем несовместные системы от систем с решениями. Если решение единственное, функция дополнительно выводит его.

# %%
function inspect_system(A, b; label="Система")
    A_float = Float64.(A)
    b_float = Float64.(b)
    rank_A = rank(A_float)
    rank_aug = rank(Float64.(hcat(A, b)))

    println("\n", label)
    println("Ранг матрицы коэффициентов: ", rank_A)
    println("Ранг расширенной матрицы: ", rank_aug)

    if rank_A < rank_aug
        println("Результат: решений нет (система несовместна).")
    elseif rank_A == size(A, 2)
        println("Результат: решение единственное.")
        println("Решение (x, y, ...): ", A_float \ b_float)
    else
        println("Результат: бесконечно много решений.")
    end
end

